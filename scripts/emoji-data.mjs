/** Writes src/core/emoji-names.<lang>.ts: every emoji the plan dialog offers, by group, with names and keywords. */
// usage: npm run emoji-data   (rerun when a new Unicode emoji version is out; bump the versions below)
// Sources: Unicode's emoji-test.txt (emojis, groups, English names) and CLDR annotations (names and
// keywords per language, the derived file for combined emojis). Left out: flags (Windows draws them as
// letters), skin tones and the hair components.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/chrome.mjs';

const EMOJI_VERSION = '16.0',
  CLDR_VERSION = '46.0.0';
const LANGS = ['en', 'sl'];
const GROUPS = {
  'Smileys & Emotion': 'smileys',
  'People & Body': 'people',
  'Animals & Nature': 'animals',
  'Food & Drink': 'food',
  'Travel & Places': 'travel',
  Activities: 'activities',
  Objects: 'objects',
  Symbols: 'symbols',
};

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}
// The file's top key is its folder name ("annotations" or "annotationsDerived").
const cldr = async (pkg, dir, lang) =>
  JSON.parse(await get(`https://cdn.jsdelivr.net/npm/${pkg}@${CLDR_VERSION}/${dir}/${lang}/annotations.json`))[dir]
    .annotations;

// [group, emoji, English name] for every fully-qualified emoji we keep, in Unicode's order.
const list = [];
let group = null;
for (const line of (await get(`https://unicode.org/Public/emoji/${EMOJI_VERSION}/emoji-test.txt`)).split('\n')) {
  const g = line.match(/^# group: (.+)$/);
  if (g) group = GROUPS[g[1].trim()] ?? null;
  const m = line.match(/^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/);
  if (group && m && !/[\u{1F3FB}-\u{1F3FF}]/u.test(m[1])) list.push([group, m[1], m[2].trim()]);
}

for (const lang of LANGS) {
  const names = {
    ...(await cldr('cldr-annotations-derived-full', 'annotationsDerived', lang)),
    ...(await cldr('cldr-annotations-full', 'annotations', lang)),
  };
  const out = {};
  let named = 0;
  for (const [g, e, en] of list) {
    const a = names[e] ?? names[e.replace(/️/g, '')];
    if (a) named++;
    const words = [...new Set([...(a?.tts ?? [lang === 'en' ? en : '']), ...(a?.default ?? []), en])]
      .filter(Boolean)
      .join(' ')
      .toLowerCase()
      .replace(/[\t\n]/g, ' ');
    (out[g] ||= []).push(`${e}\t${words}`);
  }
  const body = Object.entries(out)
    .map(([g, rows]) => `  [${JSON.stringify(g)}, ${JSON.stringify(rows.join('\n'))}],`)
    .join('\n');
  writeFileSync(
    join(ROOT, `src/core/emoji-names.${lang}.ts`),
    `/** Emojis by group with their names and keywords (${lang}); generated by scripts/emoji-data.mjs, do not edit. */\n` +
      `// Unicode emoji ${EMOJI_VERSION}, CLDR ${CLDR_VERSION}. Each group: one line per emoji, "emoji<tab>words".\n` +
      `export const EMOJI_NAMES: [group: string, rows: string][] = [\n${body}\n];\n`,
  );
  if (named < list.length * 0.95) throw new Error(`${lang}: only ${named} of ${list.length} emojis have a name`);
}
console.log(`emoji-data: ${list.length} emojis, ${LANGS.join(' + ')}`);
